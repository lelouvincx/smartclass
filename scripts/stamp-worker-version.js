import { writeFile } from 'node:fs/promises'

const commit = process.env.GITHUB_SHA

if (commit) {
  if (!/^[0-9a-f]{40}$/i.test(commit)) {
    throw new Error('GITHUB_SHA must be a full commit hash')
  }

  const contents = `// Generated by scripts/stamp-worker-version.js during deployment.\nexport const BUILD_COMMIT = '${commit.toLowerCase()}'\n`
  await writeFile(new URL('../worker/version.js', import.meta.url), contents)
}
